import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

df = pd.read_csv("2019.csv")

df.head()

df.tail()

df.shape

df.info()

df.describe()

# Check missing values
print(df.isnull().sum())

# Check duplicate rows
print("Duplicate rows:", df.duplicated().sum())

top_10 = df.sort_values(
    by="Score", ascending=False
).head(10)

print(top_10[["Country or region", "Score"]])

bottom_10 = df.sort_values(
    by="Score", ascending=True
).head(10)

print(bottom_10[["Country or region", "Score"]])

# Extract happiness scores as a NumPy array
scores = df["Score"].to_numpy()

# Calculations
mean_score = np.mean(scores)
median_score = np.median(scores)
minimum_score = np.min(scores)
maximum_score = np.max(scores)

print("Mean Happiness Score:", mean_score)
print("Median Happiness Score:", median_score)
print("Minimum Happiness Score:", minimum_score)
print("Maximum Happiness Score:", maximum_score)

print(df.columns)

if "Region" in df.columns:
    region_avg = df.groupby("Region")["Score"].mean().sort_values(ascending=False)
    print(region_avg)
else:
    print("Region column is not available in the dataset.")

highest_gdp = df.sort_values(
    by="GDP per capita", ascending=False
).head(10)

print(highest_gdp[["Country or region", "GDP per capita"]])

highest_support = df.sort_values(
    by="Social support", ascending=False
).head(10)

print(highest_support[["Country or region", "Social support"]])

happy_countries = df[df["Score"] > 7]

print(happy_countries[["Country or region", "Score"]])

low_happiness = df[df["Score"] < 4]

print(low_happiness[["Country or region", "Score"]])

print(df["Country or region"].value_counts())

plt.figure(figsize=(10, 6))

plt.bar(top_10["Country or region"], top_10["Score"])

plt.title("Top 10 Happiest Countries in 2019")
plt.xlabel("Country")
plt.ylabel("Happiness Score")
plt.xticks(rotation=45, ha="right")

plt.tight_layout()
plt.show()

plt.figure(figsize=(8, 6))

plt.scatter(df["GDP per capita"], df["Score"])

plt.title("GDP per Capita vs Happiness Score (2019)")
plt.xlabel("GDP per Capita")
plt.ylabel("Happiness Score")

plt.tight_layout()
plt.show()

